export function byKind(kind: ContentItem['kind']) {
  return contents.filter((item) => item.kind === kind)
}

export function searchContents(query: string) {
  const q = query.trim().toLowerCase()
  if (!q) return []
  return contents.filter((item) => {
    const haystack = [item.title, item.summary, item.tags.join(' '), item.category ?? '']
      .join(' ')
      .toLowerCase()
    return haystack.includes(q)
  })
}
